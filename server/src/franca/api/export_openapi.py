"""Writes the served API description to contracts/openapi.yaml.

Run after changing a route:  scripts/update-contract
"""

from pathlib import Path

import yaml

from franca.api.app import create_app

CONTRACT = Path(__file__).resolve().parents[4] / "contracts" / "openapi.yaml"
HEADER = "# Generated by  scripts/update-contract  from the server's routes. Do not edit by hand.\n"


def main() -> None:
    text = yaml.safe_dump(create_app().openapi(), sort_keys=True, allow_unicode=True)
    CONTRACT.write_text(HEADER + text, encoding="utf-8")
    print(f"Wrote {CONTRACT}")


if __name__ == "__main__":
    main()
